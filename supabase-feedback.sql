-- 个人主页 V3 反馈后台建表脚本
-- 在 Supabase Dashboard > SQL Editor 中执行（可重复执行，幂等）。
-- 课件要求（V3 第 16/18/19/24 页）：
--   1) feedback 表字段：id / name / relation / device / message / version / created_at
--   2) 开启 RLS：开启后默认拒绝，必须显式写策略
--   3) 访客(anon)只允许 INSERT，不能 SELECT / UPDATE / DELETE
--   4) 查看反馈：项目 owner 登录 Supabase 控制台 Table Editor（"不做管理员网页"）

-- 1) 建表
create table if not exists public.feedback (
  id bigint generated by default as identity primary key,  -- 唯一编号
  name text,                                                -- 昵称（可选，不要求真实姓名）
  relation text,                                            -- 与主页主人的关系：同学/老师/家人/朋友/同事/其他/不便透露
  device text,                                              -- 本条反馈针对的设备：电脑/手机/平板/其他
  message text not null,                                    -- 反馈内容（必填）
  version text not null default 'V3',                       -- 网站版本（提交时自动附带）
  created_at timestamptz not null default now(),            -- 提交时间（自动记录）
  constraint feedback_message_length check (char_length(message) between 1 and 2000),
  constraint feedback_name_length check (name is null or char_length(name) between 1 and 80)
);

-- 2) 开启行级安全（RLS）
alter table public.feedback enable row level security;

-- 3) 匿名访客只能 INSERT（字段满足约束即可写入）
drop policy if exists "anon can submit feedback" on public.feedback;
create policy "anon can submit feedback"
on public.feedback
for insert
to anon
with check (char_length(message) between 1 and 2000);

-- 4) 显式收窄权限：公开角色仅有 INSERT；不授予任何 SELECT / UPDATE / DELETE
revoke all on table public.feedback from anon;
grant insert on table public.feedback to anon;
grant usage, select on sequence public.feedback_id_seq to anon;

-- 5) 说明：反馈不会自动公开；查看请登录 Supabase 控制台 Table Editor
comment on table public.feedback is 'Private feedback from personal homepage V3 (owner views in Supabase Table Editor only)';
