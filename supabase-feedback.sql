-- 在 Supabase Dashboard > SQL Editor 中执行本文件。
-- 目标：访客可匿名写入反馈，但无法通过公开密钥读取、修改或删除任何反馈。

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  is_anonymous boolean not null default true,
  visitor_name text,
  message text not null,
  page_url text,
  user_agent text,
  constraint feedback_name_length check (visitor_name is null or char_length(visitor_name) between 1 and 80),
  constraint feedback_message_length check (char_length(message) between 1 and 2000),
  constraint feedback_identity_valid check (
    (is_anonymous = true and visitor_name is null)
    or
    (is_anonymous = false and visitor_name is not null)
  )
);

alter table public.feedback enable row level security;

-- 保证重复执行脚本时不会产生同名策略错误。
drop policy if exists "public can submit feedback" on public.feedback;

-- anon 访客只拥有 INSERT 能力，并且字段必须满足表级约束。
create policy "public can submit feedback"
on public.feedback
for insert
to anon
with check (
  char_length(message) between 1 and 2000
  and (
    (is_anonymous = true and visitor_name is null)
    or
    (is_anonymous = false and char_length(visitor_name) between 1 and 80)
  )
);

-- 明确只授权公开访客插入；不授予 SELECT / UPDATE / DELETE。
revoke all on table public.feedback from anon;
grant insert on table public.feedback to anon;
grant usage, select on sequence public.feedback_id_seq to anon;

-- 已登录的 Dashboard 管理员通过 Supabase 控制台查看数据，不需要开放公开读取策略。
comment on table public.feedback is 'Private feedback submitted from the public personal homepage';
